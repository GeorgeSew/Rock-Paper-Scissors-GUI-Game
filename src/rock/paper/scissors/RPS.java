    public void executeComputerTurn() {
        // Generate a random index between 0 and 2 (since there are 3 items)
        int index = random.nextInt(3); // Generates 0, 1, or 2
        
        // Set the computer's icon and choice string safely based on the exact index
        if (index == 0) {
            computer.setIcon(Rock.getIcon());
            computerChoice = "ROCK";
        } else if (index == 1) {
            computer.setIcon(Paper.getIcon());
            computerChoice = "PAPER";
        } else {
            computer.setIcon(Scissors.getIcon());
            computerChoice = "SCISSORS";
        }
        
        // Evaluate the round after the computer makes its choice
        determineWinner();
    }
    
    public void determineWinner() {
        // Check for a draw
        if (playerChoice.equals(computerChoice)) {
            System.out.println("It's a Draw!");
        } 
        // Check player win conditions
        else if ((playerChoice.equals("ROCK") && computerChoice.equals("SCISSORS")) ||
                 (playerChoice.equals("PAPER") && computerChoice.equals("ROCK")) ||
                 (playerChoice.equals("SCISSORS") && computerChoice.equals("PAPER"))) {
            yourScoreValue++;
            YourScore.setText(String.valueOf(yourScoreValue));
            System.out.println("You Win this round!");
        } 
        // Otherwise, computer wins
        else {
            computerScoreValue++;
            ComScore.setText(String.valueOf(computerScoreValue));
            System.out.println("Computer Wins this round!");
        }
    }

